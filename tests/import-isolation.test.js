const assert = require('node:assert/strict');
const { createStore } = require('../skyloom-store');
const values = new Map();
const storage = { getItem: key => values.get(key) ?? null, setItem: (key, value) => values.set(key, value) };
const store = createStore(storage, undefined, ['c01']);
const card = { deckId: 'c01', categoryId: 'c01', source: '測試', group: 'general', number: 1, prompt: '詞彙' };
const arcana = { ...card, deckId: 'deck-148' };
const entry = cards => ({ id: 'entry', date: new Date().toISOString(), cards });
const data = { history: [entry([card])], prompts: [card], sets: [entry([card])], decks: [{ id: 'c01', title: '測試', group: 'general', items: [{ number: 1, prompt: '詞彙' }] }], groups: ['c01'] };
store.importData({ format: 'skyloom-library', version: 1, data, legacyData: { invalid: true }, legacyRaw: 'invalid JSON' });
assert.equal(store.snapshot().prompts.length, 1);
const before = store.snapshot();
store.importData({ history: [entry([arcana])], prompts: [arcana], sets: [entry([card, arcana])], decks: [{ id: 'deck-148' }], groups: ['general', 'romance'] });
assert.deepEqual(store.snapshot(), before);
store.importData({ ...data, groups: [] });
assert.deepEqual(store.snapshot().groups, []);
values.set('creativeArcana.library.v3', JSON.stringify({ rescue: true }));
assert.deepEqual(store.exportBackup().legacyData, { rescue: true });
assert.equal(values.get('creativeArcana.library.v3'), '{"rescue":true}');
console.log('Import isolation checks passed');
